@multi_base(".copilot/session-state")
def read_copilot(home, base):
    """GitHub Copilot CLI sessions.

    Trap: several record types carry token-shaped fields and only one is usage.
    `session.shutdown` holds the authoritative per-model totals under
    modelMetrics.<model>.usage.*. The others are context-window bookkeeping —
    session.truncation (tokenLimit, preTruncationTokensInMessages,
    tokensRemovedDuringTruncation), and the currentTokens / conversationTokens /
    systemTokens snapshots. Measured on this machine: 292,157,006 real against
    555,396,004 of bookkeeping, so a naive sum reports 848,753,178 — 2.9x the
    truth. assistant.message.outputTokens is a per-message fragment already
    included in the shutdown rollup, so counting it too would double-count.

    Two things the first version of this reader dropped, both real usage:
    `usage.reasoningTokens` (335,250 here) and the compaction pass, which is a
    genuine billed model call — `session.compaction_complete` carries
    compactionTokensUsed in two schema generations that never appear in the same
    event (13 old, 5 new, 0 overlapping), so both are read and summed.

    Only known token keys are taken from that object. It also carries `duration`,
    which is MILLISECONDS — summing every integer inside a dict named
    "...TokensUsed" adds 194,163 phantom tokens, and is exactly the class of
    mistake this file exists to prevent.

    Copilot runs both vendors (gpt-5.5 and claude-*), which is why cli and
    provider are tracked separately.
    """
    if not base.is_dir():
        return []
    # Compaction token keys across both schema generations -> our field names.
    COMPACT = {"inputTokens": "input_tokens", "input": "input_tokens",
               "outputTokens": "output_tokens", "output": "output_tokens",
               "cacheReadTokens": "cache_read_input_tokens",
               "cachedInput": "cache_read_input_tokens",
               "cacheWriteTokens": "cache_creation_input_tokens"}
    # THE SESSION ID COMES OUT OF THE EVENTS, NOT OUT OF A DIRECTORY NAME.
    #
    # Copilot has written two layouts. Newer builds use <uuid>/events.jsonl;
    # older ones drop <session-uuid>.jsonl straight into session-state/. The
    # first version of this reader iterated directories only, so on a machine
    # using the flat layout it found the directory, reported zero, and looked
    # exactly like a machine where Copilot had never been run. Grouping on
    # `rel.parts[0]` fixed that and introduced a worse one: the id became
    # whatever the first path component happened to be, so a base one level
    # higher than the reader expects — an archive that keeps the whole
    # `session-state/` folder — turned EVERY session into one record called
    # "session-state". Measured against the real archive: 32 sessions and
    # 591,663,934 tokens beside the live base's 31 and 295,831,967. Exactly
    # 2.00x, and one of the sessions never existed.
    #
    # `session.start` carries data.sessionId. Checked on all 261 real files
    # here: every one carries it and every one agrees with the file name, so
    # reading it changes no number on this machine and removes the dependence
    # on where the tree is rooted. The path stays as a FALLBACK for a session
    # whose start event is missing, and `session_id_source` records which of
    # the two supplied the id, because an id read from a directory name is a
    # guess and must not look like a fact.
    per = {}
    for f in sorted(base.rglob("*.jsonl")):
        rel = f.relative_to(base)
        path_sid = (rel.parts[0][:-6]
                    if len(rel.parts) == 1 and rel.parts[0].endswith(".jsonl")
                    else rel.parts[0])
        ev_sid = None
        stamps, by_model = [], defaultdict(blank)
        models, turns = defaultdict(int), 0
        for line in open(f, encoding="utf-8", errors="ignore"):
            if '"timestamp"' not in line:
                continue
            try:
                o = json.loads(line)
            except Exception:
                continue
            ts, typ = o.get("timestamp"), o.get("type")
            if ts:
                stamps.append(ts)
            d = o.get("data") or {}
            if not isinstance(d, dict):
                d = {}
            if ev_sid is None and d.get("sessionId"):
                ev_sid = d["sessionId"]
            if typ == "assistant.message":
                turns += 1
                models[d.get("model") or "unknown"] += 1
            elif typ == "session.shutdown":
                for model, m in (d.get("modelMetrics") or {}).items():
                    u = (m or {}).get("usage") or {}
                    tgt = by_model[model]
                    tgt["input_tokens"] += u.get("inputTokens", 0) or 0
                    tgt["output_tokens"] += (u.get("outputTokens", 0) or 0)
                    # Reasoning tokens are generated and billed, and sit
                    # alongside outputTokens rather than inside it.
                    tgt["output_tokens"] += u.get("reasoningTokens", 0) or 0
                    tgt["cache_read_input_tokens"] += u.get("cacheReadTokens", 0) or 0
                    tgt["cache_creation_input_tokens"] += u.get("cacheWriteTokens", 0) or 0
            elif typ == "session.compaction_complete":
                tgt = by_model["compaction"]
                for k, v in (d.get("compactionTokensUsed") or {}).items():
                    if k in COMPACT and isinstance(v, int):
                        tgt[COMPACT[k]] += v
        if not by_model:
            continue                      # session never shut down cleanly: no usage recorded
        sid = ev_sid or path_sid
        rec = per.get(sid)
        if rec is None:
            rec = per[sid] = {
                "cli": "copilot", "session_id": sid,
                "session_id_source": "events" if ev_sid else "path",
                "account": "copilot (local)", "project": "-", "start": None,
                "end": None, "turns": 0, "tokens": blank(),
                "_models": defaultdict(int), "_stamps": []}
        elif ev_sid:
            rec["session_id_source"] = "events"
        add_source_evidence(rec, home, f)
        rec["_stamps"].extend(stamps)
        for ts in stamps:
            if rec["start"] is None or ts < rec["start"]:
                rec["start"] = ts
            if rec["end"] is None or ts > rec["end"]:
                rec["end"] = ts
        rec["turns"] += turns
        for model, n in models.items():
            rec["_models"][model] += n
        for model, t in by_model.items():
            for k in FIELDS:
                rec["tokens"][k] += t[k]
            if model != "compaction":     # a bucket, not a model — must not win the vote
                rec["_models"][model] += 1
    return [finish(rec) for rec in per.values()]


