@multi_base(".clawspring/sessions/daily")
def read_clawspring(home, base):
    """Clawspring sessions. 258,502,806 tokens that nothing counted.

    One JSON per session: {session_id, saved_at, messages[], turn_count,
    total_input_tokens, total_output_tokens}. The two token fields are the only
    ones in the format, and they are per-session totals — summable across files.

    TRAPS, and the first is the one that matters:

      REPEATED, three layers deep. sessions/history.json is an exact 20/20
        rollup of the daily files; mr_sessions/session_latest.json is a byte
        copy of one of them; and the whole tree exists FIVE times under HOME. A
        filesystem-wide *clawspring*/*.json sweep returns 205 records and
        2,585,317,850 tokens — 10.0x. Only daily/ is read, and multi_base drops
        a session_id already seen, so the copies contribute nothing.
      CUMULATIVE, ruled out. The source does `+=` a per-call
        chunk.usage.prompt_tokens, and empirically a triangular reconstruction
        of the largest session lands within 5-7% of the recorded figure while
        the cumulative counterfactual overshoots 166x.
      BOOKKEEPING, clean. max_tokens: 40000 lives in config.json, never in a
        record.

    THE RATIO IS NOT A TRAP, and this is the judgement worth writing down. The
    largest session reports 112,091,920 input tokens against 671,469 characters
    of messages — 167 tokens per character, where real text is about 0.25. That
    is not a double-count: it is the conversation re-sent on every one of 1,114
    turns and billed each time, exactly like Claude's cache_read, which is 94.7%
    of every total in this repository. Billed input is billed input.

    No model is recorded anywhere in the format, and no account. Both are said
    rather than guessed.
    """
    if not base.is_dir():
        return []
    out = []
    for f in sorted(base.rglob("session_*.json")):
        try:
            d = json.loads(f.read_text(encoding="utf-8", errors="replace"))
        except Exception:  # noqa: BLE001
            continue
        if not isinstance(d, dict) or "total_input_tokens" not in d:
            continue
        i = int(d.get("total_input_tokens") or 0)
        o = int(d.get("total_output_tokens") or 0)
        if not (i or o):
            continue
        sid = d.get("session_id") or f.stem
        rec = {"cli": "clawspring", "session_id": sid,
               "account": "clawspring (local)", "project": f.parent.name,
               "start": None, "end": None, "turns": int(d.get("turn_count") or 0),
               "tokens": blank(), "_models": defaultdict(int), "_stamps": []}
        add_source_evidence(rec, home, f)
        rec["tokens"]["input_tokens"] = i
        rec["tokens"]["output_tokens"] = o
        saved = d.get("saved_at")
        if saved:
            rec["start"] = rec["end"] = str(saved)
        out.append(finish(rec))
    return out


