def first_last_seen(home, sessions):
    """When each tool was first and last used — including where no tokens survive.

    Two independent sources, and the second is the point:

      transcripts   the sessions this scan found. Precise, but only as old as
                    whatever has not been deleted.
      editor state  VS Code's own record. `survey.usage.firstActive` is a
                    first-use date, and per-model `lastUsed` a last-use one.
                    Neither carries tokens — which is exactly why they survive
                    when the transcripts do not.

    So a tool can report a first-seen date years before its oldest surviving
    session, and that gap is real information: it is the span the token counts
    cannot speak for. The source is recorded per date so the two are never
    confused for each other.
    """
    import sqlite3
    out = {}

    def note(cli, when, src):
        if not when:
            return
        e = out.setdefault(cli, {"first": None, "last": None, "sources": []})
        if e["first"] is None or when < e["first"]:
            e["first"] = when
        if e["last"] is None or when > e["last"]:
            e["last"] = when
        if src not in e["sources"]:
            e["sources"].append(src)

    for s in sessions:
        note(s.get("cli"), s.get("start"), "transcripts")
        note(s.get("cli"), s.get("end"), "transcripts")

    def iso(ms):
        try:
            return datetime.datetime.fromtimestamp(
                ms / 1000, datetime.timezone.utc).isoformat().replace("+00:00", "Z")
        except Exception:
            return None

    for channel, db in vscode_state(home):
        try:
            con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
            rows = dict(con.execute("SELECT key, value FROM ItemTable"))
            con.close()
        except Exception:
            continue
        src = f"vscode:{channel}"

        for key, val in rows.items():
            if not isinstance(val, str):
                continue
            try:
                o = json.loads(val)
            except Exception:
                continue
            if key == "GitHub.copilot-chat" and isinstance(o, dict):
                u = (o.get("survey") or {}).get("usage") or {}
                note("copilot", iso(u.get("firstActive")), src)
                for d in (u.get("activeDays") or []):
                    note("copilot", iso(d), src)
            elif key.endswith("-usages") and isinstance(o, list):
                for item in o:
                    if isinstance(item, dict):
                        note("copilot", iso(item.get("lastUsed")), src)
            elif key == "kilocode.kilo-code" and isinstance(o, dict):
                for t in (o.get("taskHistory") or []):
                    note("kilocode", iso(t.get("ts")), src)
    return out


def read_kilocode(home, base=None):
    """Kilo Code (kilocode.kilo-code), a VS Code extension that bills per request.

    Worth reading for two reasons: it is real spend the account totals never saw,
    and because one of its requests called a Grok model, which is the clearest
    illustration of why cli and provider are separate fields: that request is
    Kilo Code spend and xAI service. Kilo Code is not Grok, and neither is
    xAI's own Grok CLI, which has its own reader below.

    Scans every VS Code channel — `Code`, `Code - Insiders`, VSCodium, and the
    OSS build. Checking only ~/.config/Code missed the Insiders profile, which is
    where the Grok usage was.

    Traps:
    - `tokensIn` ALREADY INCLUDES cacheReads and cacheWrites. The extension's own
      cost function computes uncached = tokensIn - cacheReads - cacheWrites, so
      adding them on top inflates by 64% here. Split, don't add.
    - state.vscdb's taskHistory[] is an end-of-task ROLLUP that restates these
      same per-request rows exactly. Read one or the other, never both. This
      reader takes the per-request records and ignores the rollup.

    `base` points the reader straight at a `tasks/` directory that lives
    somewhere other than a VS Code profile — the corpus keeps this store as
    `tools/kilocode/`. Without it this was the one reader that could only ever
    read the live tree, so the corpus could not be recounted for it.
    """
    if base is not None:
        return _kilocode_tasks(pathlib.Path(base), "corpus", home)
    out = []
    for label, root in vscode_roots(home):
        tasks = root / "User/globalStorage/kilocode.kilo-code/tasks"
        out.extend(_kilocode_tasks(tasks, label, home))
    return out


def _kilocode_tasks(tasks, label, home=None):
    """Every Kilo task under one `tasks/` directory, wherever that directory is."""
    out = []
    if tasks.is_dir():
        for tdir in sorted(p for p in tasks.iterdir() if p.is_dir()):
            f = tdir / "ui_messages.json"
            if not f.is_file():
                continue
            try:
                msgs = json.loads(f.read_text(encoding="utf-8", errors="ignore"))
            except Exception:
                continue
            rec = {"cli": "kilocode", "session_id": tdir.name,
                   "account": f"kilocode ({label})", "project": "-",
                   "start": None, "end": None, "turns": 0, "tokens": blank(),
                   "_models": defaultdict(int), "_stamps": []}
            add_source_evidence(rec, home, f)
            provider = None
            for m in msgs if isinstance(msgs, list) else []:
                ts = m.get("ts")
                if isinstance(ts, (int, float)):
                    iso = datetime.datetime.fromtimestamp(
                        ts / 1000, datetime.timezone.utc).isoformat().replace("+00:00", "Z")
                    rec["_stamps"].append(iso)
                    if rec["start"] is None or iso < rec["start"]:
                        rec["start"] = iso
                    if rec["end"] is None or iso > rec["end"]:
                        rec["end"] = iso
                if m.get("say") != "api_req_started":
                    continue
                try:
                    p = json.loads(m.get("text") or "{}")
                except Exception:
                    continue
                tin = p.get("tokensIn") or 0
                if not tin and not (p.get("tokensOut") or 0):
                    continue              # aborted/streaming-start placeholder row
                cr, cw = p.get("cacheReads") or 0, p.get("cacheWrites") or 0
                rec["turns"] += 1
                rec["tokens"]["input_tokens"] += max(0, tin - cr - cw)
                rec["tokens"]["cache_read_input_tokens"] += cr
                rec["tokens"]["cache_creation_input_tokens"] += cw
                rec["tokens"]["output_tokens"] += p.get("tokensOut") or 0
                provider = p.get("inferenceProvider") or provider
            if not rec["turns"]:
                continue
            rec["_models"][_kilo_model(tdir, provider)] += 1
            out.append(finish(rec))
    return out


def _kilo_model(tdir, provider):
    """Model name for a Kilo task — it lives in the sibling conversation file."""
    f = tdir / "api_conversation_history.json"
    if f.is_file():
        try:
            m = re.search(r"<model>([^<]+)</model>",
                          f.read_text(encoding="utf-8", errors="ignore")[:400000])
            if m:
                return m.group(1).split("/")[-1]
        except Exception:
            pass
    return provider or "unknown"


