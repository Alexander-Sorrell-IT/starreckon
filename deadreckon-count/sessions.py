# claude-orphans recovers Claude counters from configuration files after their
# transcripts have expired. It augments the Claude reader and has no inventory row.
PSEUDO_READERS = frozenset({"claude-orphans"})


def registry_errors(clis_doc=None, progs_doc=None, readers=None, by_label=None):
    """Return config/store/reader parity failures without changing scan behavior.

    The authored JSON is intentionally optional at runtime: `_load_inventory()`
    falls back to built-ins when either file is absent. Callers that want to
    certify the authored registry pass its parsed documents (or use the defaults).
    """
    clis_doc = _load_config("clis.json") if clis_doc is None else clis_doc
    progs_doc = _load_config("programs.json") if progs_doc is None else progs_doc
    readers = READERS if readers is None else readers
    by_label = stores.BY_LABEL if by_label is None else by_label
    if not isinstance(clis_doc, dict) or not isinstance(progs_doc, dict):
        return ["authored clis.json and programs.json are both required for validation"]

    errors, configured_readers, claimed_labels = [], set(), set()
    for source, key, doc in (("clis.json", "clis", clis_doc),
                            ("programs.json", "programs", progs_doc)):
        entries = doc.get(key)
        if not isinstance(entries, list):
           errors.append(f"{source} has no {key} list")
           continue
        for entry in entries:
           if not isinstance(entry, dict):
               errors.append(f"{source} contains a non-object entry")
               continue
           name, reader = entry.get("name", "<unnamed>"), entry.get("reader")
           if not reader:
               continue
           configured_readers.add(reader)
           if reader not in readers:
               errors.append(f"{name} points to missing reader {reader!r}")
           labels = entry.get("store_labels")
           if not isinstance(labels, list) or not labels:
               errors.append(f"{name} token-producing reader {reader!r} has no store labels")
               continue
           for label in labels:
               claimed_labels.add(label)
               store = by_label.get(label)
               if store is None:
                   errors.append(f"{name} claims missing store label {label!r}")
               elif store.cli != reader:
                   errors.append(f"{name} claims store {label!r} for {reader!r}, "
                                 f"but its cli is {store.cli!r}")
    for reader in sorted(set(readers) - PSEUDO_READERS - configured_readers):
        errors.append(f"reader {reader!r} has no registry entry")
    for label, store in sorted(by_label.items()):
        if store.cli and store.cli not in PSEUDO_READERS and label not in claimed_labels:
            errors.append(f"store {label!r} for reader {store.cli!r} has no registry entry")
    return errors


def validate_registry(clis_doc=None, progs_doc=None, readers=None, by_label=None):
    """Raise ValueError when the authored registry and the counting map diverge."""
    errors = registry_errors(clis_doc, progs_doc, readers, by_label)
    if errors:
        raise ValueError("registry validation failed: " + "; ".join(errors))


def inventory_store_mismatches(document, clis_doc=None, progs_doc=None):
    """Installed token tools whose canonical stores were not readable in a scan.

    A newly installed CLI can genuinely have no local session history, so callers
    surface this as a warning rather than treating zero rows as a corrupted scan.
    Editors and runtimes without readers are deliberately absent from this check.
    """
    clis_doc = _load_config("clis.json") if clis_doc is None else clis_doc
    progs_doc = _load_config("programs.json") if progs_doc is None else progs_doc
    entries = [
        entry for doc, key in ((clis_doc, "clis"), (progs_doc, "programs"))
        if isinstance(doc, dict)
        for entry in doc.get(key, [])
        if isinstance(entry, dict) and entry.get("reader")
    ]
    states = document.get("store_state") or {}
    installed = {
        item.get("tool") for item in document.get("inventory") or []
        if isinstance(item, dict) and item.get("installed")
    }
    missing = []
    for entry in entries:
        if entry["name"] not in installed:
            continue
        labels = entry.get("store_labels") or []
        if any((states.get(label) or {}).get("state") == stores.INSTALLED
               for label in labels):
            continue
        detail = ", ".join(
            f"{label}={(states.get(label) or {}).get('state', 'not scanned')}"
            for label in labels)
        missing.append(f"{entry['name']} ({detail})")
    return missing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="out")
    ap.add_argument("--label", default=None)
    ap.add_argument("--home", default=str(pathlib.Path.home()))
    args = ap.parse_args()

    home = pathlib.Path(args.home)
    out = pathlib.Path(args.out)
    scan_config_fingerprint = config_fingerprint()
    out.mkdir(parents=True, exist_ok=True)
    data = paths.machine(out)

    label = args.label
    if not label:
        t = paths.find(out, "totals.json") or (data / "totals.json")
        if t.exists():
            try:
                label = json.loads(t.read_text(encoding="utf-8")).get("machine")
            except Exception:
                pass
    label = label or home.name

    sessions, readers = [], []
    for name, fn in READERS.items():
        sys.stderr.write(f"reading {name} ...\n")
        sys.stderr.flush()
        err = None
        try:
            got = fn(home)
        except Exception as e:
            sys.stderr.write(f"  {name}: {e}\n")
            got, err = [], str(e)
        if name == "claude":
            # Ordering is load-bearing: claude-orphans excludes every session
            # read_claude produced, so it must see them first. READERS is an
            # ordered dict and claude-orphans is registered last.
            _ORPHAN_EXCLUDE.update(g.get("session_id") for g in got)
            for x in read_claude.excluded or []:
                sys.stderr.write(f"  excluded (not counted): {x['path']}"
                                 f" — {x['reason']}\n")
        present, checked, blind = detect(name, home)
        # THREE SENTENCES, NOT TWO. "installed, no usage recorded" over a
        # directory this user cannot enter is the exact shape of the bug:
        # a store holding a year of transcripts and a store holding nothing
        # print the same line, and the total is short with nothing anywhere
        # saying so.
        sys.stderr.write(f"  {len(got)} sessions"
                         + ("" if got else
                            (f"  (UNREADABLE: {', '.join(blind)})" if blind
                             else "  (installed, no usage recorded)" if present
                             else "  (not installed)")) + "\n")
        readers.append({
            "cli": name,
            "sessions": len(got),
            "tokens": sum(g["total"] for g in got),
            "active_min": round(sum(g.get("duration_min", 0) for g in got), 1),
            "installed": present,
            "looked_in": checked,
            "unreadable": blind,
            "error": err,
        })
        # WHICH READER PRODUCED THIS ROW. Without it a consumer cannot tell a
        # transcript-backed session from an orphan recovered out of
        # .claude.json, because both are written with cli="claude" and the
        # `transcript` flag is False on every row by the time this file is
        # read back. check_consistency then compared analyze_tokens (which
        # reads transcripts, so it CANNOT see orphans) against the sum of
        # these rows (which includes them) and called the difference a scanner
        # drift — 2,324,208,273 of it, on a machine where nothing had drifted.
        # A row that does not say where it came from cannot be reconciled
        # against a reader that only saw part of the picture.
        for g in got:
            g["source"] = name
        sessions.extend(got)

    # Join presence to usage: one row per tool, not two lists to reconcile by eye.
    by_cli = {r["cli"]: r for r in readers}
    span = {}
    for x in sessions:
        c = x.get("cli")
        st, en = x.get("start"), x.get("end")
        if not c:
            continue
        a, b = span.get(c, (None, None))
        span[c] = (min(a, st) if a and st else (a or st),
                   max(b, en) if b and en else (b or en))
    inv = inventory(home)
    # Kilo Code is one row per VS Code channel, so its usage is attributed from
    # the account each session recorded rather than from a single reader total.
    kilo = defaultdict(lambda: [0, 0, 0.0, None, None])
    for x in sessions:
        if x.get("cli") != "kilocode":
            continue
        e = kilo["Insiders" if "Insiders" in (x.get("account") or "") else "VS Code"]
        e[0] += 1
        e[1] += x["total"]
        e[2] += x.get("duration_min", 0)
        for i, k in ((3, "start"), (4, "end")):
            v = x.get(k)
            if v and (e[i] is None or (v < e[i] if i == 3 else v > e[i])):
                e[i] = v
    for item in inv:
        if item["tool"].startswith("Kilo Code ("):
            chan = item["tool"].split("(")[1].rstrip(")")
            n, tok, mins, a, b = kilo.get(chan, [0, 0, 0.0, None, None])
            item.update(counted=True, sessions_count=n, tokens=tok,
                        active_min=round(mins, 1), first_used=a, last_used=b)
            continue
        r = by_cli.get(item.get("cli") or "")
        item["counted"] = bool(r)
        if r:
            item.update(sessions_count=r["sessions"], tokens=r["tokens"],
                        active_min=r["active_min"])
            item["first_used"], item["last_used"] = span.get(item["cli"], (None, None))

    # Mark which ledger entries still have a transcript behind them.
    live = {x.get("session_id") for x in sessions if x.get("cli") == "claude"}
    ledger = read_history(home)
    for e in ledger:
        e["transcript"] = e["session_id"] in live
    lost = [e for e in ledger if not e["transcript"]]
    if lost:
        sys.stderr.write(
            f"  history ledger: {len(ledger)} sessions ever recorded, "
            f"{len(lost)} have no surviving transcript "
            f"({min((e['first_day'] or '?') for e in lost)} .. "
            f"{max((e['last_day'] or '?') for e in lost)})\n")

    sessions.sort(key=lambda s: s.get("start") or "")
    _hw_uuid = _machine_uuid(out)
    payload = {
        "machine": label,
        "generated_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        # Which code produced this. Compared across machines by
        # check_consistency.py, so a folder counted by an older scanner is
        # reported rather than silently mixed into the totals.
        "scanner_version": scanner_version(),
        # The authored inputs that governed this scan. A later configuration
        # change is detectable without hashing homes, outputs, or machine state.
        "config_fingerprint": scan_config_fingerprint,
        **( {"hardware_uuid": _hw_uuid} if _hw_uuid else {} ),
        "scanner_features": sorted(READERS),
        "uncountable_tools": probe_uncountable(home),
        # Profile-shaped directories that were FOUND and deliberately NOT
        # counted, each with its path — the author's ruling on the sandbox
        # copies. `null` would mean read_claude never ran; an empty list means
        # it ran and excluded nothing, and those are not the same statement.
        "excluded_profiles": read_claude.excluded,
        # DIRECTORIES THAT ARE THERE AND COULD NOT BE ENTERED. Not a count — a
        # count with no name cannot be acted on, and 0 is what an absent
        # directory reports too. `null` means the readers below never ran.
        # Every reader's own list is in readers[]["unreadable"]; this is the
        # union, so a consumer does not have to know the shape to see that the
        # scan was partial.
        "unreadable_paths": sorted({
            p for r in readers for p in (r.get("unreadable") or [])
        } | set(read_history.unreadable or [])
            | set(read_stats_cache.unreadable or [])
            | set(read_claude.unreadable or [])),
        # EVERY STORE'S STATE, PUBLISHED. installed | absent | unreadable.
        #
        # `unreadable_paths` above is the union of failures the READERS hit, and
        # it cannot cover a store whose directory could not be entered in the
        # first place -- no reader ever ran, so no reader reported anything, and
        # the store looks exactly like one that was never installed.
        #
        # Measured: 22 of 45 stores produced byte-for-byte identical output when
        # their directory was chmod 000 as when it was empty. Every consumer
        # asks through `bool(stores.resolve(...))`, and a boolean has two values
        # for a question with three answers. This is the signature defect of
        # this repository -- absent looks exactly like zero -- in the one place
        # it is most expensive, because it makes a tool in daily use
        # indistinguishable from a tool nobody installed.
        #
        # It matters most on the machine least able to report it: macOS denies
        # background access to Desktop and Documents and returns EPERM rather
        # than not-found, and macbook-air-m1's own profile list includes a
        # directory under Desktop. Its published scan may already be reporting
        # zeros for folders it simply could not open.
        #
        # In the ARTIFACT, not just in memory. A distinction the code makes and
        # the output drops is not a distinction anyone downstream can act on.
        "store_state": stores.scan(str(home)),
        # Every registered reader, including the ones that found nothing.
        "readers": readers,
        # When each tool was first and last used. Sourced from the transcripts
        # AND from the editor's own state, which records dates without tokens
        # and therefore outlives what it describes: Copilot's first use reads
        # 138 days earlier than its oldest surviving session on this machine.
        "first_last_seen": first_last_seen(home, sessions),
        # What is installed, whether or not this scanner can count it.
        "inventory": inv,
        # Which sessions existed, from history.jsonl, which outlives the
        # transcripts. Sessions with no surviving transcript are marked; their
        # tokens are unrecoverable but their existence is not.
        "history_ledger": ledger,
        # Claude Code's own lifetime counter per profile. Survives the cleanup
        # sweep, so it sees usage the transcripts no longer can. Reported
        # alongside them, never added to them.
        "stats_cache": read_stats_cache(home),
        "sessions": sessions,
    }
    end_config_fingerprint = config_fingerprint()
    changed_inputs = config_fingerprint_changes(
        scan_config_fingerprint, end_config_fingerprint)
    if changed_inputs:
        raise RuntimeError(
            "authored scan configuration changed during scan: "
            + ", ".join(changed_inputs)
            + "; sessions.json was not written")
    write_json_atomically(data / "sessions.json", payload)

    # Print every reader, not just the ones with rows. A CLI that found nothing
    # prints zeros and says why, so it can never quietly disappear from a report.
    print(f"{label}: {len(sessions)} sessions")
    for r in sorted(readers, key=lambda r: (-r["tokens"], r["cli"])):
        note = ""
        if not r["sessions"]:
            note = "  (not installed)" if not r["installed"] else "  (installed, no usage recorded)"
        if r.get("error"):
            note = f"  (reader failed: {r['error'][:40]})"
        print(f"  {r['cli']:12s} {r['sessions']:5d} sessions  "
              f"{r['active_min']/60:8.1f} h  {r['tokens']:>16,} tokens{note}")
    sys.stderr.write(f"\nwrote {out}/sessions.json\n")


if __name__ == "__main__":
    main()
