# codex — ~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl
# --------------------------------------------------------------------------

@multi_base(".codex/sessions")
def read_codex(home, base):
    """OpenAI Codex CLI sessions.

    Three separate traps here, each verified against the raw records rather than
    assumed, and each one produces a plausible wrong number on its own:

    1. CUMULATIVE. Every token_count event carries both `total_token_usage` (a
       running total for the session) and `last_token_usage` (that turn). Summing
       the former compounds: 59,193,380 against a true 1,453,618, 40.7x.

    2. REPEATED. `last_token_usage` is emitted TWICE per turn — the repeat is
       byte-identical and always immediately follows the first. 60 of this
       machine's 122 usage events are such repeats, so even summing the right
       field double-counts: 2,859,773 against 1,453,618, 1.97x. Only consecutive
       identical payloads are dropped; two turns that genuinely bill the same
       amount are not adjacent in the stream, and the ground truth below proves
       nothing real is lost.

    3. SUBSETS. `cached_input_tokens` is part of `input_tokens`, not a separate
       bucket (244/244 records satisfy cached <= input), and
       `reasoning_output_tokens` is likewise part of `output_tokens`. The four
       stored fields are disjoint by definition, so the cached portion is moved
       out of input rather than added on top — the split stays visible and the
       total stays right. Adding it instead inflated this machine by 2,514,176.

    Ground truth for all three: each session's FINAL total_token_usage. After
    these fixes the per-turn sum reproduces it exactly, 1,453,618 either way.
    """
    if not base.is_dir():
        return []
    out = []
    for f in sorted(base.rglob("rollout-*.jsonl")):
        rec = {"cli": "codex", "session_id": f.stem.replace("rollout-", ""),
               "account": "codex (local)", "project": "-", "start": None,
               "end": None, "turns": 0, "tokens": blank(),
               "_models": defaultdict(int), "_stamps": []}
        add_source_evidence(rec, home, f)
        prev_usage = None
        for line in open(f, encoding="utf-8", errors="ignore"):
            try:
                o = json.loads(line)
            except Exception:
                continue
            ts = o.get("timestamp")
            if ts:
                rec["_stamps"].append(ts)
                if rec["start"] is None or ts < rec["start"]:
                    rec["start"] = ts
                if rec["end"] is None or ts > rec["end"]:
                    rec["end"] = ts
            p = o.get("payload") or {}
            if o.get("type") == "turn_context":
                m = p.get("model") or (p.get("turn_context") or {}).get("model")
                if m:
                    rec["_models"][m] += 1
            if p.get("type") != "token_count":
                continue
            last = ((p.get("info") or {}).get("last_token_usage")) or {}
            if not last:
                continue
            key = json.dumps(last, sort_keys=True)
            if key == prev_usage:
                continue                  # trap 2: the re-emission of this turn
            prev_usage = key
            rec["turns"] += 1
            inp = last.get("input_tokens", 0) or 0
            cached = last.get("cached_input_tokens", 0) or 0
            rec["tokens"]["input_tokens"] += max(0, inp - cached)
            rec["tokens"]["cache_read_input_tokens"] += min(cached, inp)
            rec["tokens"]["output_tokens"] += last.get("output_tokens", 0) or 0
        if rec["turns"]:
            if not rec["_models"]:
                rec["_models"]["codex"] += 1
            out.append(finish(rec))
    return out


