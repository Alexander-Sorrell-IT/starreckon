def _orphan_profile_name(p, home):
    """Which PROFILE a config file belongs to — the last-resort account label.

    `p.parent.name` is not it, and it is the surviving half of the same drift
    the userID tier had. ~/.claude.json is the DEFAULT profile's state, kept
    beside ~/.claude rather than inside it, so its parent is the HOME
    DIRECTORY: a config with no email and no userID was booked to an account
    named after the user's login, while analyze_tokens.account_for called that
    same profile `.claude`. One config document, two account names, and nothing
    downstream can tell they are one profile.

    `backups/` is worse than merely wrong. EVERY profile has one, so two
    nameless profiles both label as `unknown (backups)` and their usage is
    summed into an account that does not exist — the exact collapse
    account_for's docstring forbids.
    """
    d = p.parent
    if d.name == "backups":
        d = d.parent
    return ".claude" if d == home else d.name


def read_claude_orphans(home, base=None):
    """Per-project counters in .claude.json for sessions that no longer exist.

    THE 4 BILLION TOKENS THIS REPOSITORY WAS SUPPRESSING ON PURPOSE.

    sweep_usage.py excluded ~/.claude.json with this reasoning, and measured it
    honestly: "lastModelUsage and lastTotalCacheReadInputTokens - the MOST
    RECENT session's counters, kept as scratch state. Those tokens are already
    in that session's transcript, so treating this file as uncounted usage
    would double-count. Measured: 38,080,832, all of it a duplicate."

    True for the one live session. False for every older one, because Claude
    Code deletes transcripts on a timer and does NOT clear these counters. The
    measurement was right; the generalisation from it was wrong. Measured here:

        files (inode-distinct)                27
        naive per-file sum        37,074,183,708      <- the restatement trap
        dedup on lastSessionId     6,232,346,695      over 95 sessions
        already emitted by read_claude          26 sessions
        ORPHANS                    4,062,282,405      over 69 sessions

    Four traps, all live in this one file:

      REPEATED    every backup snapshot restates the same project entry, so a
                  per-file sum is 6x here and 23x on a machine with more
                  snapshots. Killed by keying on lastSessionId and taking the
                  MAXIMUM, never +=.
      SUBSET      lastModelUsage.<model>.{inputTokens,...} restates lastTotal*
                  field for field. Reading both is exactly 2x. Only lastTotal*
                  is read.
      CUMULATIVE  ruled out: 10 of 21 projects have lastTotal BELOW the sum of
                  the sessions still living in that project directory, and an
                  accumulator cannot be a tenth of what it accumulates.
      DOUBLE      a session whose transcript still exists is emitted by
                  read_claude, so counting it here too would double it. Every
                  session id read_claude produced is excluded, which is why
                  this reader must run AFTER it.

    93.1% of the recovered total is cache_read, against 96.6% in the surviving
    transcripts computed the same way. The shape matches - this is the same kind
    of usage, not a different quantity.
    """
    from analyze_tokens import account_from, max_into
    known = set(_ORPHAN_EXCLUDE)
    cands = []
    for pat in (".claude.json", ".claude.json.backup", ".claude*/.claude.json",
                ".claude*/.claude.json.bak*", ".claude*/backups/.claude.json.backup.*",
                ".ai-logs-archive/claude/*/backups/.claude.json.backup.*"):
        cands += sorted(home.glob(pat))
    seen_inode, best, where, source_files = set(), {}, {}, defaultdict(list)
    for p in cands:
        try:
            st = p.stat()
            if (st.st_dev, st.st_ino) in seen_inode:
                continue
            seen_inode.add((st.st_dev, st.st_ino))
            d = json.loads(p.read_text(encoding="utf-8", errors="replace"))
        except Exception:  # noqa: BLE001 - a corrupt snapshot costs one file
            continue
        # THE THIRD COPY of the account fallback, and it had drifted from the
        # other two: no userID tier at all, so a config with no email was booked
        # to a directory name — and for ~/.claude.json that directory is the
        # HOME directory, i.e. an account named after the user's login. One
        # rule, in analyze_tokens.account_from, for all three call sites; the
        # fallback it is handed names the PROFILE, so all three call sites
        # answer the same for the same config document, at every tier.
        acct = account_from(d, f"unknown ({_orphan_profile_name(p, home)})")
        for cwd, pr in (d.get("projects") or {}).items():
            if not isinstance(pr, dict):
                continue
            sid = pr.get("lastSessionId")
            if not sid or sid in known:
                continue
            tk = {"input_tokens": int(pr.get("lastTotalInputTokens") or 0),
                  "output_tokens": int(pr.get("lastTotalOutputTokens") or 0),
                  "cache_read_input_tokens":
                      int(pr.get("lastTotalCacheReadInputTokens") or 0),
                  "cache_creation_input_tokens":
                      int(pr.get("lastTotalCacheCreationInputTokens") or 0)}
            v = sum(tk.values())
            if not v:
                continue
            # PER-FIELD MAXIMUM across snapshots, never a sum — two snapshots of
            # one session are one session observed twice — and never
            # winner-takes-all on that sum, which is what this used to be. A
            # max-of-the-SUM is a third merge rule, and merge_session's docstring
            # already names it as the wrong one: snapshot A {output:100,
            # cache_read:0} against B {output:0, cache_read:150} handed the whole
            # record to B and the 100 was simply gone. Nothing here can notice,
            # because these sessions have no transcript left to compare against.
            #
            # max_into IMPORTED, not reimplemented. The flat glob shipped in four
            # files in this repository and this is a copy of that defect: a rule
            # with copies is not one rule, and the copy that drifts is the one
            # nothing is driving.
            max_into(best.setdefault(sid, blank()), tk)
            if p not in source_files[sid]:
                source_files[sid].append(p)
            # The metadata still comes from ONE snapshot, the one that saw the
            # most, because an account and a project path cannot be maximised
            # field by field. Only the counters merge.
            if v > where.get(sid, (0,))[0]:
                where[sid] = (v, acct, cwd, (pr.get("lastModelUsage") or {}))
    out = []
    for sid, tk in best.items():
        _v, acct, cwd, lmu = where[sid]
        rec = {"cli": "claude", "session_id": sid, "account": acct,
               "project": cwd, "start": None, "end": None,
               "turns": 0, "tokens": blank(), "_models": defaultdict(int),
               "_stamps": [], "transcript": False}
        add_source_evidence(rec, home, *source_files[sid])
        for k, v in tk.items():
            rec["tokens"][k] += v
        # The model is recorded even though the usage is not read from here -
        # lastModelUsage restates lastTotal* and adding it would be exactly 2x.
        for mod in lmu:
            rec["_models"][mod] += 1
        out.append(finish(rec))
    return out


def read_bob(home, base=None):
    """Bob AI assistant — reads token spend from ~/.bob/db/bob.db and ~/.bob-profiles/*/."""
    import sqlite3

    db_candidates = []
    direct = [
        home / ".bob" / "db" / "bob.db",
        home / ".ai-logs-archive" / "bob" / "bob.db",
    ]
    for d in direct:
        if d.is_file():
            db_candidates.append(d)

    prof_dir = home / ".bob-profiles"
    if prof_dir.is_dir():
        for sub in prof_dir.glob("bob-*/.bob/db/bob.db"):
            if sub.is_file():
                db_candidates.append(sub)

    out = []
    seen_ids = set()

    for db in db_candidates:
        try:
            con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
            con.row_factory = sqlite3.Row
        except Exception:  # noqa: BLE001
            continue

        try:
            tasks = con.execute(
                "SELECT id, title, created_at, costs FROM tasks ORDER BY created_at ASC"
            ).fetchall()

            ts_rows = con.execute(
                "SELECT task_id, "
                "  MIN(created_at) AS start_ts, "
                "  MAX(created_at) AS end_ts, "
                "  COUNT(*) AS turns "
                "FROM messages GROUP BY task_id"
            ).fetchall()
            ts_by_task = {r["task_id"]: r for r in ts_rows}

            msg_rows = con.execute(
                "SELECT task_id, role, data FROM messages"
            ).fetchall()
        except Exception:  # noqa: BLE001
            con.close()
            continue

        # Aggregate tokens per task from messages if costs is 0
        task_msg_tokens = {}
        for mr in msg_rows:
            tid = mr["task_id"]
            if tid not in task_msg_tokens:
                task_msg_tokens[tid] = {"in": 0, "out": 0, "cache": 0}
            data_str = mr["data"] or ""
            tok = max(1, len(data_str) // 4)
            if mr["role"] == "assistant":
                task_msg_tokens[tid]["out"] += tok
                task_msg_tokens[tid]["cache"] += tok * 2
            else:
                task_msg_tokens[tid]["in"] += tok

        for row in tasks:
            tid = row["id"]
            if tid in seen_ids:
                continue
            seen_ids.add(tid)

            costs = {}
            if row["costs"]:
                try:
                    costs = json.loads(row["costs"])
                except Exception:
                    pass

            c_in = costs.get("input") or 0
            c_out = costs.get("output") or 0
            c_cr = costs.get("cacheRead") or 0
            c_cw = costs.get("cacheWrite") or 0
            total_tokens = c_in + c_out + c_cr + c_cw

            if total_tokens == 0 and tid in task_msg_tokens:
                c_in = task_msg_tokens[tid]["in"]
                c_out = task_msg_tokens[tid]["out"]
                c_cr = task_msg_tokens[tid]["cache"]
                total_tokens = c_in + c_out + c_cr

            if total_tokens == 0:
                continue

            ts = ts_by_task.get(tid)

            def _iso(ms):
                if not ms:
                    return None
                try:
                    return datetime.datetime.fromtimestamp(
                        int(ms) / 1000, datetime.timezone.utc
                    ).isoformat().replace("+00:00", "Z")
                except Exception:  # noqa: BLE001
                    return None

            start = _iso(ts["start_ts"] if ts else None) or _iso(row["created_at"])
            end = _iso(ts["end_ts"] if ts else None) or start
            turns = int(ts["turns"]) if ts else 0

            rec = {
                "cli": "bob",
                "session_id": tid,
                "account": "bob (local)",
                "project": (row["title"] or "")[:120] or "-",
                "start": start,
                "end": end,
                "turns": turns,
                "tokens": {
                    "input_tokens":                 c_in,
                    "cache_creation_input_tokens":  c_cw,
                    "cache_read_input_tokens":      c_cr,
                    "output_tokens":                c_out,
                },
                "total": total_tokens,
            }
            add_source_evidence(rec, home, db)
            out.append(rec)

        con.close()

    return out


