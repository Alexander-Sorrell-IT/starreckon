def scanner_version():
    """A fingerprint of the code that produced these numbers.

    A content hash rather than a hand-bumped constant, because a constant only
    works if someone remembers to change it, and the failure is silent when they
    do not. Any edit to the counting logic changes this automatically.

    It exists because the consistency checks cannot catch version skew. They ask
    whether each slice sums to its whole, and a machine scanned with an older
    scanner is internally consistent and differently counted - every check
    passes while two folders quietly disagree about what a token is. Recording
    the version is the only thing that makes "these were counted the same way"
    checkable at all.
    """
    import hashlib
    h = hashlib.sha256()
    here = pathlib.Path(__file__).parent
    for name in ("sessions.py", "analyze_tokens.py"):
        f = here / name
        if f.is_file():
            h.update(f.read_bytes())
    return h.hexdigest()[:12]


SCAN_CONFIG_INPUTS = ("clis.json", "programs.json", "accounts.json", "cli-config.json")


def config_fingerprint(root=None):
    """Return a stable digest of authored inputs that govern this scan.

    Missing configuration is a supported fallback, but it must remain distinct
    from a present empty file: the former selects built-in behavior while the
    latter is still an authored input.
    """
    root = pathlib.Path(root) if root is not None else pathlib.Path(__file__).resolve().parent
    files = {}
    for name in SCAN_CONFIG_INPUTS:
        try:
            content = (root / name).read_bytes()
        except FileNotFoundError:
            files[name] = {"state": "missing"}
        except OSError:
            # A scan can still use its graceful fallback when an authored file
            # cannot be read, but the persisted provenance must say so.
            files[name] = {"state": "unreadable"}
        else:
            files[name] = {
                "state": "present",
                "sha256": hashlib.sha256(content).hexdigest(),
            }
    encoded = json.dumps(files, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return {
        "fingerprint_version": 1,
        "algorithm": "sha256",
        "sha256": hashlib.sha256(encoded).hexdigest(),
        "files": files,
    }


def config_fingerprint_changes(before, after):
    """Names of authored scan inputs whose fingerprint states differ."""
    before_files = before.get("files", {}) if isinstance(before, dict) else {}
    after_files = after.get("files", {}) if isinstance(after, dict) else {}
    return [name for name in SCAN_CONFIG_INPUTS
            if before_files.get(name) != after_files.get(name)]


def write_json_atomically(path, document):
    """Write a JSON document without exposing a partial replacement."""
    path = pathlib.Path(path)
    temp_path = None
    try:
        with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=path.parent,
                prefix=f".{path.name}.", suffix=".tmp", delete=False) as fh:
            temp_path = pathlib.Path(fh.name)
            json.dump(document, fh, indent=1)
            fh.write("\n")
        os.replace(temp_path, path)
    finally:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink()


def _machine_uuid(mdir=None):
    """The hardware_uuid for a machine folder, or None.

    Reads the UUID that update.py wrote into .machine-id, so every generated
    file agrees with the anchor check_consistency already uses. Falls back to
    install.hardware_uuid() when .machine-id does not exist yet (first scan,
    or a temp directory in tests).

    None is a legitimate return: a machine without a UUID is not an error, and
    nothing downstream must crash on it. check_consistency skips the UUID check
    for machines with no anchor.
    """
    if mdir is not None:
        mid = pathlib.Path(mdir) / ".machine-id"
        try:
            info = json.loads(mid.read_text(encoding="utf-8"))
            uuid = info.get("hardware_uuid")
            if uuid:
                return uuid
        except Exception:
            pass
    try:
        from install import hardware_uuid as _hw_uuid
        return _hw_uuid()
    except Exception:
        return None


def stamped(doc, mdir=None):
    """Stamp a document with the scanner version and hardware UUID.

    Every artifact, not just totals.json and sessions.json. Measured after the
    field was introduced: it reached 2 of the 5 machine-readable files, so
    hardware.json, lifetime.json and stats.json carried numbers that could not
    be traced to the code that produced them — and a number whose provenance is
    unknown is a number that cannot be compared to another machine's.

    That gap is exactly what the field was added to close. It was created three
    minutes after a scan silently lost 4,691,850,175 tokens, precisely so a
    figure could be tied to a scanner; leaving three of five files unstamped
    reopened the same hole in the files nobody thought to check.

    One helper rather than the same line copied into three writers: this
    codebase has shipped the same defect four separate times by duplicating a
    rule instead of sharing it.

    hardware_uuid is read from .machine-id (the anchor check_consistency.py
    checks against) and is None when the folder has not been claimed yet.
    """
    if isinstance(doc, dict):
        doc["scanner_version"] = scanner_version()
        uuid = _machine_uuid(mdir)
        if uuid:
            doc["hardware_uuid"] = uuid
    return doc


def blank():
    return dict.fromkeys(FIELDS, 0)


def total(t):
    return sum(t[k] for k in FIELDS)


def iso_to_dt(s):
    if not s:
        return None
    try:
        return datetime.datetime.fromisoformat(s.replace("Z", "+00:00"))
    except Exception:
        return None


def active_minutes(stamps, threshold=None):
    """Minutes of work: consecutive gaps, discarding idle stretches.

    The threshold is a judgement call and the result moves with it. Measured
    over 104,537 real inter-turn gaps on one machine:

        1 min -> 117.9 h      15 min -> 286.0 h      60 min -> 407.4 h

    So roughly 59% of the reported figure comes from gaps between 1 and 15
    minutes, which are genuinely ambiguous - reading output looks exactly like
    walking away. 15 is defensible because 96.4% of gaps are under 1 minute and
    the p99 is 4.1, so the threshold only adjudicates a thin tail. It is not
    "true" though, and `duration_tight_min` is recorded alongside it so the
    number can be read as the range it actually is rather than a point.

    What makes this bounded at all is having 104,537 intermediate events. An
    editor that records only a launch and a last write has two points and no
    threshold can rescue it, which is why editors report launches and not hours.
    """
    ts = sorted(t for t in (iso_to_dt(s) for s in stamps) if t)
    cap = MAX_ACTIVE_GAP_MIN if threshold is None else threshold
    mins = 0.0
    for a, b in zip(ts, ts[1:]):
        gap = (b - a).total_seconds() / 60
        if 0 < gap <= cap:
            mins += gap
    return round(mins, 1)


_SOURCE_DIGEST_CACHE = {}

def source_evidence(home, files):
    """Stable, non-content evidence for files that supplied a session's tokens."""
    home = pathlib.Path(home).resolve() if home is not None else None
    out = []
    for f in files:
        f = pathlib.Path(f)
        try:
            resolved = f.resolve()
            path = "~/" + resolved.relative_to(home).as_posix() if home else str(resolved)
        except ValueError:
            path = str(resolved)
        except OSError:
            continue
        try:
            st = f.stat()
            cache_key = (str(resolved), st.st_size, st.st_mtime_ns)
            if cache_key in _SOURCE_DIGEST_CACHE:
                digest_hex = _SOURCE_DIGEST_CACHE[cache_key]
            else:
                digest = hashlib.sha256()
                with f.open("rb") as fh:
                    for chunk in iter(lambda: fh.read(1024 * 1024), b""):
                        digest.update(chunk)
                digest_hex = digest.hexdigest()
                _SOURCE_DIGEST_CACHE[cache_key] = digest_hex
            item = {"path": path, "bytes": st.st_size, "sha256": digest_hex}
        except OSError:
            continue
        if item not in out:
            out.append(item)
    return sorted(out, key=lambda item: (item["path"], item["bytes"], item["sha256"]))


def add_source_evidence(rec, home, *files):
    """Add every contributing file once; merged sessions retain every contributor."""
    sources = rec.setdefault("sources", [])
    for item in source_evidence(home, files):
        if item not in sources:
            sources.append(item)
    sources.sort(key=lambda item: (item["path"], item["bytes"], item["sha256"]))


def finish(rec):
    """Derive duration and the sent/received split once a session is complete."""
    stamps = rec.pop("_stamps", [])
    rec["duration_min"] = active_minutes(stamps)
    # The same session under a 1-minute threshold: a hard floor on how much of
    # this is unambiguously work rather than a gap someone chose to call work.
    rec["duration_tight_min"] = active_minutes(stamps, 1)
    rec["elapsed_min"] = None
    a, b = iso_to_dt(rec.get("start")), iso_to_dt(rec.get("end"))
    if a and b and b >= a:
        rec["elapsed_min"] = round((b - a).total_seconds() / 60, 1)
    t = rec["tokens"]
    rec["total"] = total(t)
    rec["sent"] = sum(t[k] for k in SENT_FIELDS)
    rec["received"] = sum(t[k] for k in RECEIVED_FIELDS)
    models = rec.pop("_models", {})
    rec["model"] = max(models, key=models.get) if models else "unknown"
    rec["provider"] = provider_of(rec["model"])
    # Counted in every token total; excluded only where the question is spend.
    rec["billed"] = is_billed(rec.get("cli"), rec["provider"])
    return rec


