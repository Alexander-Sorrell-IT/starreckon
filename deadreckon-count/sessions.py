@multi_base(".grok/sessions", ".grok/archived_sessions")
def read_grok(home, base):
    """xAI Grok CLI sessions.

    Not installed on this machine, so this reader returns nothing here — it is
    written for the other machines in the fleet. Two different tools share the
    name and only one records usage: @vibe-kit/grok-cli (community npm package)
    stores none, while xAI's official Grok Build CLI writes JSON-RPC session
    updates to ~/.grok/{sessions,archived_sessions}/<url-encoded-cwd>/<id>/.

    Traps, from the published record format:
    - Only `turn_completed` updates are end-of-turn totals. `usage_snapshot` is
      a mid-turn snapshot carrying the SAME field names; counting both
      double-counts every turn.
    - usage.inputTokens/outputTokens is the SUM over usage.modelUsage.<model>.*.
      Take the per-model breakdown when present, the top level only as fallback.
    - cachedReadTokens is a subset of inputTokens and reasoningTokens a subset of
      outputTokens, matching xAI's OpenAI-compatible convention.
    - params._meta.totalTokens is a running CONTEXT counter, not billed usage.
    """
    out = []
    for sdir in sorted(p for p in base.glob("*/*") if p.is_dir()):
        f = sdir / "updates.jsonl"
        if not f.is_file():
            continue
        rec = {"cli": "grok", "session_id": sdir.name, "account": "grok (local)",
               "project": urllib.parse.unquote(sdir.parent.name), "start": None,
               "end": None, "turns": 0, "tokens": blank(),
               "_models": defaultdict(int), "_stamps": []}
        add_source_evidence(rec, home, f)
        for line in open(f, encoding="utf-8", errors="ignore"):
            try:
                o = json.loads(line)
            except Exception:
                continue
            ts = o.get("timestamp")
            if isinstance(ts, (int, float)):
                ts = datetime.datetime.fromtimestamp(
                    ts if ts < 1e11 else ts / 1000,
                    datetime.timezone.utc).isoformat().replace("+00:00", "Z")
            if isinstance(ts, str) and ts:
                rec["_stamps"].append(ts)
                if rec["start"] is None or ts < rec["start"]:
                    rec["start"] = ts
                if rec["end"] is None or ts > rec["end"]:
                    rec["end"] = ts
            upd = ((o.get("params") or {}).get("update")) or {}
            if upd.get("sessionUpdate") != "turn_completed":
                continue              # usage_snapshot would double-count
            usage = upd.get("usage") or {}
            per_model = usage.get("modelUsage") or {}
            rows = list(per_model.items()) or [("grok", usage)]
            rec["turns"] += 1
            for model, u in rows:
                if not isinstance(u, dict):
                    continue
                rec["_models"][model] += 1
                inp = u.get("inputTokens", 0) or 0
                cached = u.get("cachedReadTokens", 0) or 0
                rec["tokens"]["input_tokens"] += max(0, inp - cached)
                rec["tokens"]["cache_read_input_tokens"] += min(cached, inp)
                rec["tokens"]["output_tokens"] += u.get("outputTokens", 0) or 0
        if rec["turns"]:
            out.append(finish(rec))
    return out


