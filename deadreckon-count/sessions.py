#!/usr/bin/env python3
"""Per-session records for every AI CLI on this machine.

`analyze_tokens.py` answers "how many tokens per account". This answers "which
session, how long, how heavy" — the per-session detail needed to rank anything.
It writes `sessions.json` into a machine folder; `stats.py` queries it.

Two dimensions are tracked separately and must not be conflated:

    cli       which tool you paid for   claude | copilot | codex | gemini
    provider  which vendor served it    anthropic | openai | deepseek | google

Copilot runs Claude models; that usage is Copilot spend, not Anthropic
subscription spend, so it is attributed to `cli=copilot, provider=anthropic`.
Filtering by cli answers "what did this subscription cost me"; filtering by
provider answers "whose model actually ran".

Every reader below had a trap that produces a plausible but wrong number, and
each one is documented at its reader. Verified against raw records, not assumed.

Usage:
    python3 sessions.py --out <machine-folder>
"""

