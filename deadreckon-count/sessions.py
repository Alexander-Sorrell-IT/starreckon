# gemini — ~/.gemini/tmp/<projectHash>/chats/session-<ts>-<id>.json
# --------------------------------------------------------------------------

def _gemini_docs(f):
    """Session documents from a Gemini chat file, whichever way it is written.

    A whole-file JSON object, or JSON Lines where each line may be a full
    session or a single message. Anything unparseable is skipped rather than
    aborting the file — one truncated line in a live session must not cost the
    whole conversation.
    """
    try:
        text = f.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return
    try:
        d = json.loads(text)
        yield d if isinstance(d, dict) else {"messages": d}
        return
    except Exception:
        pass
    loose = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            o = json.loads(line)
        except Exception:
            continue
        if isinstance(o, dict) and isinstance(o.get("messages"), list):
            yield o
        elif isinstance(o, dict):
            loose.append(o)          # a bare message record
    if loose:
        yield {"messages": loose}


@multi_base(".gemini/tmp")
def read_gemini(home, base):
    """Google Gemini CLI sessions.

    This reader exists because the previous version of this repo declared Gemini
    uncountable. That was wrong by 1,468,362,549 tokens — the single largest
    error the project has made. The claim rested on grepping ~/.gemini for
    "token" and finding mostly anyio's CapacityLimiter.total_tokens (concurrency
    slots) in 27 vendored library files, then stopping. The real usage was in a
    directory that grep never reached, recorded under the Gemini API's own field
    names.

    Two traps, both confirmed across all 4,559 usage records here:

    - `cached` (cachedContentTokenCount) is a SUBSET of `input`
      (promptTokenCount), not a separate bucket. Adding it inflates by
      1,221,557,506 — 83%. It is moved out of input instead, keeping the total
      right and the cache split visible.
    - `total` (totalTokenCount) already equals input + output + thoughts + tool.
      Summing it alongside its own components is exactly 2x.

    Sessions must be grouped by the `sessionId` field, NOT per file: one session
    is checkpointed across up to 12 files, and 92 files here hold 52 sessions.
    Counting files as sessions would triple the session count and wreck every
    per-session duration.
    """
    if not base.is_dir():
        return []
    sessions = {}
    # Both extensions and any depth. The first version required exactly
    # <hash>/chats/session-*.json, so on a machine where Gemini writes .jsonl it
    # found ~/.gemini/tmp, read nothing, and was indistinguishable from Gemini
    # never having been used. A reader should be picky about what a token IS,
    # not about where the file sits.
    files = sorted(set(base.rglob("session-*.json")) | set(base.rglob("session-*.jsonl"))
                   | set(base.rglob("chats/*.json")) | set(base.rglob("chats/*.jsonl")))
    for f in files:
        for d in _gemini_docs(f):
            sid = d.get("sessionId") or f.stem
            rec = sessions.get(sid)
            if rec is None:
                rec = sessions[sid] = {
                    "cli": "gemini", "session_id": sid, "account": "gemini (local)",
                    "project": d.get("projectHash") or "-", "start": None, "end": None,
                    "turns": 0, "tokens": blank(), "_models": defaultdict(int),
                    "_stamps": []}
            add_source_evidence(rec, home, f)
            for m in d.get("messages") or []:
                ts = m.get("timestamp")
                if ts:
                    rec["_stamps"].append(ts)
                    if rec["start"] is None or ts < rec["start"]:
                        rec["start"] = ts
                    if rec["end"] is None or ts > rec["end"]:
                        rec["end"] = ts
                t = m.get("tokens")
                if not isinstance(t, dict):
                    continue
                rec["turns"] += 1
                if m.get("model"):
                    rec["_models"][m["model"]] += 1
                inp = t.get("input", 0) or 0
                cached = t.get("cached", 0) or 0
                rec["tokens"]["input_tokens"] += max(0, inp - cached) + (t.get("tool", 0) or 0)
                rec["tokens"]["cache_read_input_tokens"] += min(cached, inp)
                # Thinking tokens are generated and billed as output.
                rec["tokens"]["output_tokens"] += (t.get("output", 0) or 0) + (t.get("thoughts", 0) or 0)
    return [finish(r) for r in sessions.values() if r["turns"]]


