@multi_base(*stores.paths_for("copilot-chat", "copilot-chat-insiders",
                              "copilot-chat-empty", "copilot-chat-empty-insiders"))
def read_copilot_chat(home, base):
    """GitHub Copilot Chat in VS Code. 2.29 GB that nothing read.

    Not the same product as ~/.copilot, which read_copilot handles — verified
    disjoint: 75 chatSessions ids against 274 CLI session ids, intersection 0.
    NO_TOKENS_BECAUSE labelled VS Code "an editor — hosts agents, spends no
    tokens itself". That is wrong, and this reader is the correction.

    THE FIELD, and the path is exact because a plausible wrong one returns zero:

        requests[].result.metadata.toolCallRounds[].thinking.tokens

    An earlier reading gave it as response[].thinking.tokens; a reader written
    to that path finds nothing. All 7,210 occurrences are under requests[].

    WHAT THE NUMBER IS AND IS NOT. It is reasoning tokens —
    usage.completion_tokens_details.reasoning_tokens — which is definitionally
    a SUBSET of output. There is no output counter anywhere in these 2.29 GB
    (a byte-level grep for inputTokens|outputTokens|promptTokens|totalTokens|
    usage returns zero), so nothing is double-counted by including it today.
    It is banked as reasoning, not folded into output_tokens, so that the day a
    Copilot build starts persisting real usage this does not silently become 2x.

    IT IS A FLOOR, AND AN APPROXIMATE ONE. 7,196 of 7,210 values are exact
    multiples of 64 — the store rounds. 3,523 rounds report 0 while still
    carrying a real encrypted reasoning blob, and only 1,134 of 4,427 requests
    carry any figure at all. So this counts what the store records, which is
    less than what was billed.

    TRAPS:
      BOOKKEEPING is the live one. inputState.selectedModel.metadata.
        max{Input,Output}Tokens are context-window advertisements, and with the
        state.vscdb equivalents a naive "sum every token key" gives 12,586,912
        against 1,214,160 real — 10.4x.
      CUMULATIVE ruled out: 382 of 450 multi-round requests contain a DECREASE
        across rounds, and reading only the last value undercounts by 7.4x.
      REPEATED ruled out on the record's own identity: 7,210 blocks, 7,210
        distinct thinking.id, zero reused.

    THE RATIO IS THE OPPOSITE OF THE USUAL TRAP. 2.29 GB of transcript for 1.2 M
    tokens is far too LOW — this store persists the conversation and never
    persists the billed input. A recording gap, not an inflation.
    """
    if not base.is_dir():
        return []
    files = []
    if base.name == "emptyWindowChatSessions":
        files = sorted(base.glob("*.json"))
    else:
        for ws in sorted(p for p in base.iterdir() if p.is_dir()):
            files += sorted((ws / "chatSessions").glob("*.json")) \
                if (ws / "chatSessions").is_dir() else []
    out = []
    for f in files:
        try:
            d = json.loads(f.read_text(encoding="utf-8", errors="replace"))
        except Exception:  # noqa: BLE001 - one 54 MB file is truncated on disk
            continue
        sid = d.get("sessionId") or f.stem
        rec = {"cli": "copilot-chat", "session_id": sid,
               "account": d.get("requesterUsername") or "copilot-chat",
               "project": f.parent.parent.name, "start": None, "end": None,
               "turns": 0, "tokens": blank(), "_models": defaultdict(int),
               "_stamps": []}
        add_source_evidence(rec, home, f)
        seen_think = set()
        for req in d.get("requests") or []:
            rounds = ((req.get("result") or {}).get("metadata") or {}).get("toolCallRounds") or []
            for r in rounds:
                th = r.get("thinking") or {}
                n = th.get("tokens")
                tid = th.get("id")
                if not isinstance(n, int) or n <= 0:
                    continue
                if tid:
                    if tid in seen_think:
                        continue
                    seen_think.add(tid)
                rec["turns"] += 1
                # Reasoning is inside output. Banked in output_tokens because
                # this store has no output figure for it to be inside OF — the
                # docstring records why that stops being true if one appears.
                rec["tokens"]["output_tokens"] += n
                mod = r.get("model") or req.get("modelId")
                if mod:
                    rec["_models"][str(mod)] += 1
        if rec["turns"]:
            out.append(finish(rec))
    return out


