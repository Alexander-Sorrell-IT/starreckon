# Directories that hold copies of records rather than a tool's live storage, or
# that are too big to be worth walking. Skipped when searching for tool storage.
SKIP_DIRS = {"node_modules", ".git", "corpus", "merged", "deadreckon-record",
             "archive", "snap", ".cache", "venv", ".venv", "__pycache__",
             "site-packages", ".Trash", "Trash"}


def tool_roots(home, rels, max_depth=4):
    """Every directory on this machine holding one tool's session records.

    Each reader used to be a single hardcoded `home / ".<tool>/..."`. That is
    one guess at where a tool keeps its data, and silence when the guess is
    wrong — the failure that read Copilot as 0 on flat-layout machines, Gemini
    as 0 where it writes .jsonl, and every VS Code-hosted tool as "not
    installed" off Linux. The same shape was still in seven readers after those
    were fixed one at a time.

    So: look in the canonical place, honour the XDG overrides, and then walk the
    home directory to `max_depth` for a directory of the same name anywhere else
    — a second checkout, a copied profile, a staging tree. On the machine this
    was written on, four copied Claude profiles under ~/Desktop held 817,889,443
    tokens that existed in no live profile, because a copy resets mtime and the
    tool's own cleanup never reaches it.

    Returns real directories only, deduplicated by resolved path so a symlink
    and its target are not both walked.
    """
    seen, out = set(), []

    def add(p):
        try:
            key = p.resolve()
        except OSError:
            return
        if key in seen or not p.is_dir():
            return
        seen.add(key)
        out.append(p)

    rels = [r.replace("~/", "").lstrip("/") for r in rels]
    for rel in rels:
        add(home / rel)

    # THE TOOL'S OWN RELOCATION VARIABLE, which is a different thing from XDG
    # and moves more. $CODEX_HOME, $COPILOT_HOME, $GEMINI_CLI_HOME and
    # $CLAUDE_CONFIG_DIR each replace the whole dotdir, not a prefix of it, and
    # each can point outside the home directory entirely — at which point the
    # walk below cannot find it either, because the walk starts at home. So the
    # reader read zero, the store map resolved to [], and a tool in daily use
    # was reported identically to a tool nobody installed.
    #
    # stores.RELOCATIONS is the one definition; asking it here rather than
    # restating it is the whole reason stores.py exists.
    for rel in rels:
        for extra in stores.relocations(rel, str(home)):
            add(pathlib.Path(extra))

    for var, prefix in (("XDG_CONFIG_HOME", ".config"), ("XDG_DATA_HOME", ".local/share")):
        root = os.environ.get(var)
        if not root:
            continue
        for rel in rels:
            add(pathlib.Path(root).expanduser() / rel)
            if rel.startswith(prefix + "/"):        # ~/.config/X -> $XDG/X
                add(pathlib.Path(root).expanduser() / rel[len(prefix) + 1:])

    # The leading component is the tool's own directory name — that is what is
    # searched for elsewhere, with the rest of the path re-applied beneath it.
    wanted = {}
    for rel in rels:
        parts = rel.split("/")
        wanted.setdefault(parts[0], set()).add("/".join(parts[1:]))

    def walk(root, depth):
        if depth < 0:
            return
        try:
            kids = sorted(root.iterdir())
        except OSError:
            return
        for d in kids:
            if not d.is_dir() or d.is_symlink() or d.name in SKIP_DIRS:
                continue
            if d.name in wanted:
                for tail in wanted[d.name]:
                    add(d / tail if tail else d)
            walk(d, depth - 1)

    walk(home, max_depth)
    return out


def merge_session(dst, src):
    """Two observations of ONE session, merged to the union of what they saw.

    Per-field MAXIMUM on the counters, via analyze_tokens.max_into — the same
    rule read_claude applies to two writes of one message, asked here of two
    copies of one session. Not a sum: the copies overlap and summing them
    doubles. Not first-wins, which is what this used to do.

    Not max-of-the-sum either, which is the third rule this repository invented
    (read_claude_orphans) and the reason max_into is per FIELD: snapshot A
    {output:100, cache_read:0} against B {output:0, cache_read:150} makes B win
    wholesale under max-of-the-sum and the 100 is simply gone.

    Everything else follows the same shape — the earliest start, the latest end,
    the largest turn count and duration — and the model is taken from whichever
    copy saw more turns, because a truncated copy's vote is a worse vote.
    """
    from analyze_tokens import max_into
    if (src.get("turns") or 0) > (dst.get("turns") or 0):
        for k in ("model", "provider", "account", "project", "billed"):
            if k in src:
                dst[k] = src[k]
    max_into(dst["tokens"], src["tokens"])
    for k in ("turns", "duration_min", "duration_tight_min", "elapsed_min", "end"):
        a, b = dst.get(k), src.get(k)
        if b is not None and (a is None or b > a):
            dst[k] = b
    a, b = dst.get("start"), src.get("start")
    if b is not None and (a is None or b < a):
        dst["start"] = b
    for k, v in src.items():
        if dst.get(k) is None and v is not None:
            dst[k] = v
    for item in src.get("sources", []):
        if item not in dst.setdefault("sources", []):
            dst["sources"].append(item)
    if "sources" in dst:
        dst["sources"].sort(
            key=lambda item: (item.get("path", ""), item.get("bytes", 0),
                              item.get("sha256", "")))
    t = dst["tokens"]
    dst["total"] = total(t)
    dst["sent"] = sum(t[k] for k in SENT_FIELDS)
    dst["received"] = sum(t[k] for k in RECEIVED_FIELDS)
    return dst


def multi_base(*rels, key="session_id"):
    """Run a reader against every location its tool's data was found in.

    The reader keeps its body and takes the base directory as an argument. This
    wrapper supplies each one in turn and merges the results.

    UNION WITH MAXIMUM, not first-wins. This used to be `if k in seen:
    continue`, so whichever location the walk reached first supplied the whole
    session and the rest of the record was thrown away. That is right for a pure
    copy and wrong for the copies that actually exist, because retention deleted
    the tail of one of them: driven against read_codex, a full 6-turn rollout
    plus a truncated copy of it gives 675 one way round and 110 the other — an
    83.7% loss decided by which directory the copy happens to sit in. A number
    that moves when nothing but the filesystem layout moves is not a
    measurement.

    `wrapper.rels` is published so a caller that has the SAME data somewhere
    else — the corpus, an archive — can work out which sub-path of that copy is
    this reader's base, instead of a hand-written second table. A hand-written
    table is how the counter and the corpus ended up covering different ground
    without either one saying so.
    """
    def deco(fn):
        @functools.wraps(fn)
        def wrapper(home, base=None):
            if base is not None:
                return fn(home, base)
            out, seen = [], {}
            for b in tool_roots(home, rels):
                for rec in fn(home, b) or []:
                    k = rec.get(key)
                    if k is None:
                        out.append(rec)
                        continue
                    if k in seen:
                        merge_session(seen[k], rec)
                        continue
                    seen[k] = rec
                    out.append(rec)
            return out
        wrapper.rels = rels
        return wrapper
    return deco


def _probe(p, blind, want="dir"):
    """is_dir()/is_file() that survives EACCES and NAMES what it could not read.

    pathlib suppresses ENOENT, ENOTDIR, EBADF and ELOOP and RE-RAISES EACCES.
    That is the correct default everywhere else and it is fatal here: `chmod
    000` on one profile took sessions.py down with

        PermissionError: [Errno 13] Permission denied:
        '<home>/.claude/history.jsonl'

    out of read_history(), which main() calls OUTSIDE the per-reader
    try/except. The run then wrote no sessions.json at all while
    analyze_tokens.py exited 0 on the same tree, and check_consistency ran
    EIGHT FEWER CHECKS against the machine folder left holding totals.json
    alone — a crash that presents as a quieter, cleaner audit.

    `blind` is a required argument and there is no swallow-only path.
    Answering False and saying nothing would make an unreadable profile report
    identically to one that was never there, which is the bug this repository
    has now shipped seven times in four disguises.
    """
    try:
        return p.is_dir() if want == "dir" else p.is_file()
    except PermissionError:
        blind.append(str(p))
        return False
    except OSError:
        return False


def _jsonl_under(root, blind):
    """Every *.jsonl below `root`, plus the directories that would not open.

    `Path.rglob` and `Path.glob` swallow EACCES and yield nothing — there is no
    flag, no callback and no exception. `os.walk(onerror=...)` is the only walk
    in the standard library that hands the scandir failure back, which is why
    it is here and not the one-liner it replaced.
    """
    out = []
    def onerror(err):
        blind.append(str(getattr(err, "filename", None) or root))
    for dirpath, _dirnames, filenames in os.walk(str(root), onerror=onerror):
        for name in filenames:
            if name.endswith(".jsonl"):
                out.append(pathlib.Path(dirpath) / name)
    return out


def read_stats_cache(home):
    """Claude Code's own lifetime token counter, which outlives the transcripts.

    Each profile keeps stats-cache.json, and it is not a transcript, so the
    cleanup sweep does not touch it. It holds modelUsage.<model> with all four
    billed counters, accumulated since firstSessionDate — including sessions
    whose transcripts were deleted months ago.

    Measured on this machine, per profile:

        ~/.claude       cache 12,290,485,337   transcripts  5,547,678,789
        ~/.claude-alt   cache 11,440,918,343   transcripts  2,564,843,440

    Two fields that look contradictory and are not. dailyModelTokens is input +
    output ONLY, no cache, which is why it sums to 30,779,997 against
    modelUsage's 12,290,485,337 — a 399x gap that looks like corruption until
    you check: modelUsage's input+output alone is 30,779,997 exactly, matching
    to the token. Different units, not different answers.

    NOT merged into the transcript totals, and that is deliberate. The cache is
    lifetime-to-lastComputedDate while the transcripts are whatever survives, so
    the two overlap by an amount that cannot be determined — the per-day
    breakdown excludes cache reads, which are ~99% of the volume. Adding them
    would double-count; picking one would discard real usage the other holds.
    Both are reported, each labelled with what it covers.
    """
    F = ("inputTokens", "outputTokens", "cacheReadInputTokens",
         "cacheCreationInputTokens")
    out, blind = [], []
    read_stats_cache.unreadable = blind
    for cfg in sorted(home.glob(".*claude*")):
        f = cfg / "stats-cache.json"
        if not (_probe(cfg, blind) and _probe(f, blind, "file")):
            continue
        try:
            d = json.loads(f.read_text(encoding="utf-8", errors="ignore"))
        except Exception:
            continue
        mu = d.get("modelUsage") or {}
        by_model = {m: sum(v.get(k, 0) or 0 for k in F) for m, v in mu.items()}
        out.append({
            "profile": cfg.name,
            "account": _claude_account(cfg, home),
            "total": sum(by_model.values()),
            "input_output_only": sum((v.get("inputTokens", 0) or 0)
                                     + (v.get("outputTokens", 0) or 0)
                                     for v in mu.values()),
            "by_model": by_model,
            "sessions": d.get("totalSessions"),
            "messages": d.get("totalMessages"),
            "first_session": (d.get("firstSessionDate") or "")[:10] or None,
            "last_computed": d.get("lastComputedDate"),
        })
    return out


def read_history(home):
    """The session ledger from each profile's history.jsonl.

    Transcripts are deleted; this is not. history.jsonl holds one record per
    prompt with a sessionId, a timestamp and a project, and it reaches months
    further back than the transcripts do — on this machine to 2026-01-14 where
    the oldest surviving transcript is 2026-05-05.

    It carries NO token counts, so it cannot recover what a lost session cost.
    What it does give is proof that the session existed, when, and in which
    project. That converts "we may have lost some data" into a number.

    Captured into the machine folder and committed, so the ledger accumulates
    permanently even as the transcripts behind it expire. This is the only part
    of the record that survives its own source.

    Prompt text is deliberately NOT stored. `display` and `pastedContents` hold
    what was typed, and a token counter has no business keeping that.
    """
    out, blind = [], []
    read_history.unreadable = blind
    for cfg in sorted(home.glob(".*claude*")):
        f = cfg / "history.jsonl"
        if not (_probe(cfg, blind) and _probe(f, blind, "file")):
            continue
        account = _claude_account(cfg, home)
        per = {}
        for line in f.open(encoding="utf-8", errors="ignore"):
            try:
                o = json.loads(line)
            except Exception:
                continue
            sid = o.get("sessionId")
            if not sid:
                continue
            ts = o.get("timestamp")
            day = None
            if isinstance(ts, (int, float)):
                try:
                    day = datetime.datetime.fromtimestamp(
                        ts / 1000 if ts > 1e11 else ts,
                        datetime.timezone.utc).date().isoformat()
                except Exception:
                    pass
            elif isinstance(ts, str):
                day = ts[:10]
            e = per.setdefault(sid, {"session_id": sid, "account": account,
                                     "profile": cfg.name, "project": o.get("project"),
                                     "first_day": day, "last_day": day, "prompts": 0})
            e["prompts"] += 1
            if day:
                if not e["first_day"] or day < e["first_day"]:
                    e["first_day"] = day
                if not e["last_day"] or day > e["last_day"]:
                    e["last_day"] = day
        out.extend(per.values())
    return out


def read_claude(home):
    """Claude Code sessions.

    Trap: a turn can appear twice — resuming rewrites earlier turns into the new
    file, and a subagent's turns are inlined into its parent as sidechain
    records. Both copies carry the same message uuid, so dedupe on it or the
    total inflates. Subagent and workflow transcripts are separate API
    conversations and DO count; a flat glob over projects/*/*.jsonl misses them.
    """
    out = []
    # The SAME discovery analyze_tokens uses, imported rather than repeated.
    # This function kept its own `home.glob(".*claude*")` after every other
    # reader had been widened, so the two scanners disagreed about which
    # profiles exist: 11,407,255,540 against 10,415,507,939 on one machine,
    # 991,747,601 apart, which is the four profiles under ~/Desktop that a home
    # glob cannot see. check_consistency caught it — "analyze_tokens ==
    # sessions" exists for exactly this, two implementations of one question.
    from analyze_tokens import find_config_dirs, MessageMax
    # One collator for the WHOLE machine, and one record per session id no
    # matter which profile it was found in. Widening discovery without this
    # counted the four copied profiles as extra work: 765 sessions and
    # 37,196,921,021 tokens against analyze_tokens' 11,414,194,297 — the same
    # conversations, four times. A per-record map cannot see across profiles,
    # so the copies each looked new.
    #
    # THE SAME OBJECT analyze_tokens.scan uses. There were two implementations
    # of this rule and they disagreed by 37,175 tokens on a single message.
    mm = MessageMax()
    per = {}
    # Profiles found and deliberately not counted, kept with their paths so
    # main() can publish them. A list, set on every call: `None` here means
    # read_claude has not run, which is not the same as "nothing was excluded".
    excluded = []
    # DIRECTORIES THAT ARE THERE AND WILL NOT OPEN. rglob swallows EACCES and
    # yields nothing, so an unreadable project directory inside a perfectly
    # readable profile subtracted 1,251,500 tokens from the fixture and every
    # partition still summed to its whole — thirty consistency checks, byte for
    # byte identical against the same tree with that directory left readable
    # and EMPTY. Walked with os.walk(onerror=...) because that is the only one
    # of the three walks in the standard library that will tell you.
    blind = []
    read_claude.unreadable = blind
    for cfg in find_config_dirs(home, excluded=excluded):
        account = _claude_account(cfg, home)
        root = cfg / "projects"
        try:
            projs = sorted(p for p in root.iterdir() if p.is_dir())
        except PermissionError:
            blind.append(str(root))
            projs = []
        except OSError:
            projs = []
        for proj in projs:
            for f in sorted(_jsonl_under(proj, blind)):
                touched_sids = set()
                for line in open(f, encoding="utf-8", errors="ignore"):
                    if '"usage"' not in line:
                        continue
                    try:
                        o = json.loads(line)
                    except Exception:
                        continue          # truncated final line in a live session
                    msg = o.get("message") or {}
                    usage = msg.get("usage")
                    if not isinstance(usage, dict):
                        continue
                    sid = o.get("sessionId") or f.stem
                    rec = per.get(sid)
                    if rec is None:
                        rec = per[sid] = {
                            "cli": "claude", "session_id": sid, "account": account,
                            "project": proj.name, "start": None, "end": None,
                            "turns": 0, "tokens": blank(), "_models": defaultdict(int),
                            "_seen": set(), "_stamps": [],
                        }
                    touched_sids.add(sid)
                    # Dedup on message.id, crediting a running MAXIMUM — the
                    # rule itself lives in analyze_tokens.MessageMax and this
                    # reader runs that object rather than a second copy of it.
                    #
                    # Fixing only one scanner made them disagree, which the
                    # cross-check caught immediately:
                    #
                    #   FAIL analyze_tokens == sessions on HP Laptop Linux
                    #        14,619,003,145 != 6,608,178,238
                    #
                    # Measured on ~/.claude-alt: 33,790 rows, 33,790 distinct row
                    # uuids — a row-uuid dedup removed NOTHING — against 13,819
                    # real messages. Claude Code rewrites one message many times
                    # while streaming, each write a new row uuid with the same
                    # message.id.
                    model = msg.get("model") or "unknown"
                    ts = o.get("timestamp")
                    if ts:
                        rec["_stamps"].append(ts)
                        if rec["start"] is None or ts < rec["start"]:
                            rec["start"] = ts
                        if rec["end"] is None or ts > rec["end"]:
                            rec["end"] = ts
                    key = mm.key(f, msg.get("id"), o.get("uuid"),
                                 (sid, ts or "", model), usage)
                    # A turn is counted only when the message is new: a rewrite
                    # is the same turn, and so is the copy of it that a second
                    # profile holds.
                    delta, _meta, new = mm.credit(key, usage)
                    if new:
                        rec["turns"] += 1
                        rec["_models"][model] += 1
                    for k in FIELDS:
                        rec["tokens"][k] += delta[k]
                for sid in touched_sids:
                    add_source_evidence(per[sid], home, f)
    # Emitted once, after every profile has been read — `per` is keyed by
    # session id across all of them, so a session found in a live profile and
    # again in a copy is one record holding the union of both.
    for rec in per.values():
        rec.pop("_seen", None)
        out.append(finish(rec))
    read_claude.excluded = excluded
    return out


# Filled in by read_claude on every call; None until it has run once, so
# "never scanned" cannot be read as "nothing was excluded".
read_claude.excluded = None
# Same idiom, same reason: a reader that could not enter a directory has to
# be able to say so before it is ever called, or `None` and `[]` become the
# question instead of the answer.
read_history.unreadable = None
read_stats_cache.unreadable = None
read_claude.unreadable = None


