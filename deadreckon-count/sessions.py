# Which counters are billed as sent to the model vs generated by it. Cache reads
# dominate every total by an order of magnitude, so a bare "tokens" number hides
# that ~99% of it is context being re-read rather than work being produced.
SENT_FIELDS = ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens")
RECEIVED_FIELDS = ("output_tokens",)

# Active time, not elapsed time. A resumed session's transcript can span days
# while holding minutes of actual work, so first-to-last timestamp measures
# calendar drift: it produced a "436 hour day" on this machine. Sum the gaps
# between consecutive turns and ignore any gap longer than the idle threshold,
# matching how Claude Code itself segments sessions.
MAX_ACTIVE_GAP_MIN = 15

# Providers whose models run on this machine. The tokens are real and counted
# like any others — a token is a token regardless of who pays for it — but no
# invoice exists, so they are marked unbilled rather than excluded.
#
# Three independent dimensions, and conflating any two produces a wrong number:
#   cli       which tool you paid for       claude | copilot | ollama | ...
#   provider  whose model actually ran      anthropic | google | meta | ...
#   billed    whether money changed hands   True | False
# Copilot running Claude is GitHub spend and Anthropic service. Ollama running
# llama is nobody's spend and Meta's model. Both are tokens.
LOCAL_PROVIDERS = {"ollama", "lmstudio", "local"}


def is_billed(cli, provider):
    """False when the model ran on this machine, so no invoice exists."""
    return not (cli in LOCAL_PROVIDERS or provider in LOCAL_PROVIDERS)


