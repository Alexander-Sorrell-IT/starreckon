# Google's Antigravity CLI stores usage as unnamed protobuf fields, and puts the
# two largest conversations in encrypted files. The key below is a string
# constant compiled into the `agy` binary (found at file offset 0x4ab02c9,
# alongside the symbols proto_saver.WithEncryptionKey and hasEncryption), so
# there is no secret being exfiltrated here — it is the same fixed key shipped
# to every user, which is why the files can be read at all.
AGY_KEY = b"safeCodeiumworldKeYsecretBalloon"

# Field numbers inside the ModelUsageStats submessage (field 9 of a step's
# metadata). Names come from the FileDescriptorProtos embedded in the binary.
AGY_UNCACHED, AGY_OUTPUT, AGY_CACHED = 2, 3, 5
AGY_OUT_PART_A, AGY_OUT_PART_B, AGY_REQUEST_ID = 9, 10, 11


def _pb_varint(b, i):
    r = s = 0
    while True:
        if i >= len(b):
            raise ValueError
        c = b[i]
        i += 1
        r |= (c & 0x7F) << s
        s += 7
        if not c & 0x80:
            return r, i
        if s > 70:
            raise ValueError


def _pb_fields(b):
    """Parse one protobuf message level, or None if it is not one.

    Requires the parse to consume the buffer EXACTLY. Without that, arbitrary
    binary decodes as a plausible-looking message and yields enormous fake
    "token counts" — a first attempt at this reported 1.49e21 tokens.
    """
    d, i = {}, 0
    while i < len(b):
        try:
            tag, i = _pb_varint(b, i)
        except ValueError:
            return None
        fn, wt = tag >> 3, tag & 7
        if fn == 0 or fn > 536870911:
            return None
        try:
            if wt == 0:
                v, i = _pb_varint(b, i)
            elif wt == 1:
                v, i = b[i:i + 8], i + 8
            elif wt == 2:
                ln, i = _pb_varint(b, i)
                if i + ln > len(b):
                    return None
                v, i = b[i:i + ln], i + ln
            elif wt == 5:
                v, i = b[i:i + 4], i + 4
            else:
                return None
        except (ValueError, IndexError):
            return None
        d.setdefault(fn, []).append(v)
    return d if i == len(b) else None


def _agy_usage(blob, out, depth=0):
    """Collect every ModelUsageStats found anywhere inside a step's metadata."""
    if depth > 14:
        return out
    d = _pb_fields(blob)
    if not d:
        return out
    for fn, vals in d.items():
        for v in vals:
            if not isinstance(v, bytes) or len(v) < 2:
                continue
            inner = _pb_fields(v)
            if not inner:
                continue
            if fn == 9:
                def g(k, _f=inner):
                    v = _f.get(k, [0])[0]
                    return v if isinstance(v, int) else 0
                unc, o, cac = g(AGY_UNCACHED), g(AGY_OUTPUT), g(AGY_CACHED)
                a, bb = g(AGY_OUT_PART_A), g(AGY_OUT_PART_B)
                # Structural signature of a real usage record: the output total
                # equals its two components. Everything else at field 9 is a
                # coincidental match, and this is what separates them.
                if (unc or o or cac) and a + bb == o and max(unc, o, cac) < 50_000_000:
                    rid = inner.get(AGY_REQUEST_ID, [None])[0]
                    key = rid if isinstance(rid, bytes) else (unc, o, cac, a, bb)
                    out[key] = (unc, o, cac)
                    continue
            _agy_usage(v, out, depth + 1)
    return out


def _agy_times(blob, out, depth=0):
    """Every google.protobuf.Timestamp nested anywhere inside a trajectory.

    A Timestamp is {1: seconds} with an optional {2: nanos} and nothing else,
    so it is identifiable by shape without the .proto. Three guards keep this
    from collecting coincidence: the message must contain only fields 1 and 2,
    be at most 12 bytes, and hold a plausible epoch second.

    Walking nested rather than reading the top level matters for the encrypted
    .pb files: those are a whole trajectory in one blob, so the top level has a
    single time and every per-step time is buried. Those two files hold 88% of
    Antigravity's tokens here, and both reported a duration of 0 without this.
    On the SQLite conversations, where the top-level read already worked, this
    is a strict superset — verified per conversation, none lost time.
    """
    if depth > 12:
        return out
    d = _pb_fields(blob)
    if not d:
        return out
    for vals in d.values():
        for v in vals:
            if not isinstance(v, bytes) or len(v) < 2:
                continue
            inner = _pb_fields(v)
            if not inner:
                continue
            sec = inner.get(1, [None])[0]
            if (isinstance(sec, int) and 1_500_000_000 < sec < 2_500_000_000
                    and len(v) <= 12 and set(inner).issubset({1, 2})):
                out.append(sec)
            else:
                _agy_times(v, out, depth + 1)
    return out


def _agy_decrypt(raw):
    """AES-256-GCM with a 12-byte nonce prefix, or None if it cannot be read."""
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    except ImportError:
        return None
    try:
        return AESGCM(AGY_KEY).decrypt(raw[:12], raw[12:], None)
    except Exception:
        return None


# A model id as Antigravity writes it, which is NOT the public Gemini naming:
# gemini-3.6-flash-high, gemini-3-flash-a, gemini_coder, gemini-3.5-flash-low.
# Underscores and letter suffixes are normal, so a pattern demanding a digit
# straight after the dash misses most of them.
AGY_MODEL = re.compile(rb"gemini[-_][0-9A-Za-z][0-9A-Za-z._\-]{0,26}")
# Rejected because they match that shape and are not models: filenames, and the
# gemini-cli-* extension packages.
AGY_NOT_MODEL = re.compile(rb"\.(json|md|zip|txt|py|js)$|^gemini-cli")


def _agy_model(con):
    """The model for a conversation, from gen_metadata where it is recorded.

    Read from the field that holds it rather than by scanning the whole
    conversation. Scanning finds `used_claude_conservative` (a feature flag) and
    `claude-alt.md` (one of the user's own filenames) and reports Antigravity as
    having run Claude models, which it did not — every conversation on this
    machine resolves to Gemini. Substring matches are not model attribution.
    """
    try:
        rows = [bytes(r[0]) for r in con.execute("select data from gen_metadata") if r[0]]
    except Exception:
        return None
    best = defaultdict(int)
    for b in rows:
        for m in AGY_MODEL.findall(b):
            if AGY_NOT_MODEL.search(m):
                continue
            best[m.decode("ascii", "ignore").rstrip("-._")] += 1
    if not best:
        return None
    # Prefer the most specific id: the longest one, which carries the tier
    # suffix (gemini-3.6-flash-high over gemini-3.6-flash).
    return max(best, key=lambda k: (len(k), best[k]))


@multi_base(".gemini/antigravity-cli/conversations")
def read_antigravity(home, base):
    """Google Antigravity CLI conversations.

    Two storage forms, both counted:

      conversations/<uuid>.db   SQLite; usage is a protobuf BLOB in steps.metadata
      conversations/<uuid>.pb   the same protobuf, AES-256-GCM encrypted

    Traps, every one of them a duplicate of the authoritative record rather than
    new usage. Reading all of them sums to exactly 4.00x the truth:

      steps.step_payload 5.9.*      == steps.metadata 9.* (embedded copy)
      steps.metadata 28.2.*         == steps.metadata 9.* (in-blob mirror)
      gen_metadata.data 1.4.*       a strict SUBSET of steps.metadata 9.*
      gen_metadata.data 1.17.2.*    byte-identical mirror of 1.4.*
      fields 9 and 10               components of field 3, not additions

    Only steps.metadata field 9 is read, deduplicated on the per-request server
    id in field 11, because the same request appears in several steps.

    This depends on an undocumented key and unnamed field numbers, so it is the
    one reader here that a vendor update can silently break. It fails soft: a
    conversation it cannot parse contributes nothing and is reported, rather
    than being counted as zero.
    """
    if not base.is_dir():
        return []
    import sqlite3
    out, unreadable = [], 0
    for f in sorted(list(base.glob("*.db")) + list(base.glob("*.pb"))):
        usage, stamps, secs, models = {}, [], [], defaultdict(int)
        if f.suffix == ".db":
            try:
                con = sqlite3.connect(f"file:{f}?mode=ro", uri=True)
                rows = con.execute("select metadata from steps").fetchall()
                named = _agy_model(con)
                con.close()
            except Exception:
                unreadable += 1
                continue
            blobs = [r[0] for r in rows if isinstance(r[0], (bytes, bytearray))]
            if named:
                models[named] += 1000        # authoritative: outvotes any scan
        else:
            plain = _agy_decrypt(f.read_bytes())
            if plain is None:
                unreadable += 1
                continue
            blobs = [plain]
        for b in blobs:
            b = bytes(b)
            _agy_usage(b, usage)
            # Fallback for the encrypted .pb files, which have no gen_metadata
            # table to read. Same pattern, same exclusions.
            for m in AGY_MODEL.findall(b):
                if not AGY_NOT_MODEL.search(m):
                    models[m.decode("ascii", "ignore").rstrip("-._")] += 1
            _agy_times(b, secs)
        stamps = [datetime.datetime.fromtimestamp(x, datetime.timezone.utc)
                  .isoformat().replace("+00:00", "Z") for x in sorted(set(secs))]
        if not usage:
            continue
        unc = sum(v[0] for v in usage.values())
        o = sum(v[1] for v in usage.values())
        cac = sum(v[2] for v in usage.values())
        rec = {"cli": "antigravity", "session_id": f.stem,
               "account": "antigravity (local)", "project": "-",
               "start": None, "end": None, "turns": len(usage),
               "tokens": blank(), "_models": models or {"antigravity": 1},
               "_stamps": stamps}
        add_source_evidence(rec, home, f)
        rec["tokens"]["input_tokens"] = unc
        rec["tokens"]["cache_read_input_tokens"] = cac
        rec["tokens"]["output_tokens"] = o
        if stamps:
            rec["start"], rec["end"] = min(stamps), max(stamps)
        else:
            # No decodable step times. Fall back to the file's mtime for WHEN,
            # but leave start == end so active_minutes reports 0 rather than
            # inventing a span. The earlier version did this for every
            # conversation, which gave all 19 a duration of exactly 0 — that
            # reads as "no time spent" instead of "not measured".
            try:
                ts = datetime.datetime.fromtimestamp(
                    f.stat().st_mtime, datetime.timezone.utc).isoformat().replace("+00:00", "Z")
                rec["start"] = rec["end"] = ts
            except Exception:
                pass
        out.append(finish(rec))
    if unreadable:
        sys.stderr.write(f"  antigravity: {unreadable} conversation(s) unreadable "
                         f"(install `cryptography` to read encrypted .pb)\n")
    return out


